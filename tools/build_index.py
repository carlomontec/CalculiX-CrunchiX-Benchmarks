"""Generate the README tables of this repository from its run.json files.

Every result folder holds a ``run.json`` (and, for benchmarks, a
``results.json`` written by the benchmark runner of the code repository).
This script

* writes ``README.md`` inside every benchmark folder (metadata, timings,
  memory and the agreement of the solvers' results), and
* rewrites the index between the ``<!-- index:start -->`` and
  ``<!-- index:end -->`` markers of the top-level ``README.md``.

Tables are never edited by hand: change the JSON files and run

    python3 tools/build_index.py           # rewrite the generated files
    python3 tools/build_index.py --check   # exit 1 if they are out of date
"""

from __future__ import annotations

import argparse
import json
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
START, END = "<!-- index:start -->", "<!-- index:end -->"
GENERATED = "<!-- Generated by tools/build_index.py from run.json and results.json. Do not edit by hand. -->"

# result fields compared between solvers, per benchmark entry
CHECK_GROUPS = ("static_verification", "total_effective_mass")
SOLVER_ORDER = ("MUMPS", "PARDISO", "ACCELERATE", "PASTIX", "SPOOLES")


def load(path: Path):
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def rel(path: Path) -> str:
    return path.relative_to(ROOT).as_posix()


def runs(kind: str):
    """All run.json files of one kind, newest first, then by path."""
    found = []
    for p in sorted(ROOT.rglob("run.json")):
        if ".git" in p.parts:
            continue
        meta = load(p)
        if meta.get("kind") == kind:
            found.append((p.parent, meta))
    return sorted(found, key=lambda x: (x[1].get("date", ""), rel(x[0])), reverse=True)


def solvers_sorted(names):
    return sorted(names, key=lambda s: (SOLVER_ORDER.index(s) if s in SOLVER_ORDER else 99, s))


def fmt_time(seconds):
    return f"{seconds:.1f}" if seconds is not None else "failed"


def fmt_gb(mb):
    return f"{mb / 1024:.1f}" if mb else "n/a"


def check_values(entry):
    vals = {}
    for group in CHECK_GROUPS:
        for k, v in (entry.get(group) or {}).items():
            if isinstance(v, (int, float)) and not isinstance(v, bool):
                vals[f"{group}.{k}"] = float(v)
    return vals


def agreement(results):
    """Largest relative difference of every solver/thread entry against one reference entry."""
    solvers = solvers_sorted(results)
    ref_solver = solvers[0]
    ref_threads = max(results[ref_solver], key=int)
    ref = check_values(results[ref_solver][ref_threads])
    if not ref:
        return None, []
    rows = []
    for s in solvers:
        for t in sorted(results[s], key=int):
            e = results[s][t]
            if not e.get("success"):
                rows.append((s, t, None))
                continue
            vals = check_values(e)
            worst = 0.0
            for k, r in ref.items():
                if k in vals:
                    scale = max(abs(r), 1e-30)
                    worst = max(worst, abs(vals[k] - r) / scale)
            rows.append((s, t, worst))
    return f"{ref_solver}, {ref_threads} threads", rows


def md_value(v):
    if v is None:
        return "not recorded"
    if isinstance(v, list):
        return "<br>".join(f"`{x}`" if x.startswith("python") else x for x in v)
    return str(v)


def benchmark_readme(folder: Path, meta: dict) -> str:
    data = load(folder / "results.json")
    results = data["results"]
    solvers = solvers_sorted(results)
    threads = sorted({int(t) for r in results.values() for t in r})
    m, mach, code = meta["model"], meta["machine"], meta["code"]

    out = [GENERATED, "", f"# {meta['title']}", ""]
    out += ["| | |", "|:---|:---|"]
    out.append(f"| Date | {meta['date']} |")
    model_link = os.path.relpath(ROOT / m["source"], folder)
    out.append(f"| Model | [`{m['name']}`]({model_link}/), deck `{m['deck']}`, {m['analysis']} |")
    out.append(f"| Mesh | {m['mesh'].replace('_', '-')}: {m['nodes']:,} nodes, {m['elements']:,} elements, "
               f"{m['equations']:,} equations |")
    out.append(f"| Machine | {mach['cpu']}, {mach['ram_gb']} GB RAM, {mach['os']}"
               + (f", {mach['compiler']}" if mach.get("compiler") else "") + " |")
    commit = f" at `{code['commit']}`" if code.get("commit") else ""
    out.append(f"| Code | `{code['ref']}`{commit}, version {code['version']}"
               + (f" ({code['note']})" if code.get("note") else "") + " |")
    if meta.get("build"):
        out.append("| Build | " + "<br>".join(f"{k}: {v}" for k, v in meta["build"].items()) + " |")
    else:
        out.append("| Build | not recorded |")
    out.append(f"| Command | {md_value(meta.get('command'))} |")
    out.append("")

    out += ["## Wall time and peak memory", "",
            "Wall time in seconds; peak resident memory in GB in brackets. "
            "Threads = `OMP_NUM_THREADS`.", ""]
    out.append("| Threads | " + " | ".join(solvers) + " |")
    out.append("|---:|" + "---:|" * len(solvers))
    for t in threads:
        cells = []
        for s in solvers:
            e = results[s].get(str(t))
            if e is None:
                cells.append("")
            elif not e.get("success"):
                cells.append("failed")
            else:
                cells.append(f"{fmt_time(e['wall_time'])} ({fmt_gb(e.get('peak_rss_mb'))})")
        out.append(f"| {t} | " + " | ".join(cells) + " |")
    out.append("")

    ref_label, rows = agreement(results)
    if ref_label:
        groups = sorted({k.split(".")[0] for s in results for e in results[s].values()
                         for k in check_values(e)})
        out += ["## Agreement of the results", "",
                f"Largest relative difference of the checked quantities ({', '.join(f'`{g}`' for g in groups)}) "
                f"against {ref_label}, over all thread counts. "
                "*Identical* means equal to all digits written by ccx.", ""]
        out.append("| Solver | Thread counts | Max. relative difference |")
        out.append("|:---|:---|---:|")
        for s in solvers_sorted({r[0] for r in rows}):
            mine = [r for r in rows if r[0] == s]
            ts = ", ".join(r[1] for r in mine)
            if any(r[2] is None for r in mine):
                worst = "failed"
            else:
                w = max(r[2] for r in mine)
                worst = "identical" if w == 0.0 else f"{w:.1e}"
            out.append(f"| {s} | {ts} | {worst} |")
        out.append("")

    if meta.get("notes"):
        out += ["## Notes", ""] + [f"- {n}" for n in meta["notes"]] + [""]
    out += ["## Files", "",
            "- [`results.json`](results.json): raw output of the benchmark runner",
            "- [`run.json`](run.json): metadata of this run", ""]
    return "\n".join(out)


def best_time(results, solver):
    ok = [e["wall_time"] for e in results.get(solver, {}).values() if e.get("success")]
    return min(ok) if ok else None


def index() -> str:
    out = [START, GENERATED, ""]

    out += ["### Release verification", "",
            "| Date | Report | Result |", "|:---|:---|:---|"]
    for folder, meta in runs("report"):
        if rel(folder).startswith("releases/"):
            out.append(f"| {meta['date']} | [{meta['title']}]({rel(folder)}/REPORT.md) | {meta['summary']} |")
    out.append("")

    out += ["### Benchmarks", "",
            "Fastest wall time per solver over all thread counts, in seconds. "
            "Follow the link for timings per thread count, memory and result agreement.", ""]
    all_solvers = solvers_sorted({s for f, _ in runs("benchmark") for s in load(f / "results.json")["results"]})
    out.append("| Date | Model | Equations | Machine | " + " | ".join(all_solvers) + " |")
    out.append("|:---|:---|---:|:---|" + "---:|" * len(all_solvers))
    for folder, meta in runs("benchmark"):
        res = load(folder / "results.json")["results"]
        cells = [fmt_time(best_time(res, s)) if s in res else "" for s in all_solvers]
        m = meta["model"]
        out.append(f"| {meta['date']} | [{m['name']}, {m['mesh'].replace('_', '-')}]({rel(folder)}/) "
                   f"| {m['equations']:,} | {meta['machine']['label']} | " + " | ".join(cells) + " |")
    out.append("")

    out += ["### Other reports", "", "| Date | Report | Result |", "|:---|:---|:---|"]
    for folder, meta in runs("report"):
        if not rel(folder).startswith("releases/"):
            out.append(f"| {meta['date']} | [{meta['title']}]({rel(folder)}/REPORT.md) | {meta['summary']} |")
    out.append("")

    out += ["### Studies", "", "| Date | Study | Summary |", "|:---|:---|:---|"]
    for folder, meta in runs("study"):
        out.append(f"| {meta['date']} | [{meta['title']}]({rel(folder)}/) | {meta['summary']} |")
    out += ["", END]
    return "\n".join(out)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="only check that generated files are up to date")
    args = ap.parse_args()

    targets = {}
    for folder, meta in runs("benchmark"):
        targets[folder / "README.md"] = benchmark_readme(folder, meta)

    readme = ROOT / "README.md"
    text = readme.read_text(encoding="utf-8")
    if START not in text or END not in text:
        print(f"README.md has no {START} ... {END} block", file=sys.stderr)
        return 2
    head, rest = text.split(START, 1)
    tail = rest.split(END, 1)[1]
    targets[readme] = head + index() + tail

    stale = []
    for path, content in targets.items():
        old = path.read_text(encoding="utf-8") if path.exists() else None
        if old != content:
            stale.append(rel(path))
            if not args.check:
                path.write_text(content, encoding="utf-8")
    if args.check:
        for p in stale:
            print(f"out of date: {p}")
        return 1 if stale else 0
    for p in stale:
        print(f"updated: {p}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
